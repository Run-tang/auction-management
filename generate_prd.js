// ========== 辅助函数 ==========
function border(color = GRAY_BORDER, size = 4) {
  return { style: BorderStyle.SINGLE, size, color };
}

function allBorders(color = GRAY_BORDER, size = 4) {
  const b = border(color, size);
  return { top: b, bottom: b, left: b, right: b };
}

function noBorder() {
  const nb = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  return { top: nb, bottom: nb, left: nb, right: nb };
}

function cell(text, opts = {}) {
  const {
    w = 2000, bold = false, color = "000000", bg = WHITE,
    align = AlignmentType.LEFT, size = 18, colspan = 1,
    valign = VerticalAlign.CENTER, borders = allBorders()
  } = opts;
  return new TableCell({
    borders,
    width: { size: w, type: WidthType.DXA },
    columnSpan: colspan,
    verticalAlign: valign,
    shading: { fill: bg, type: ShadingType.CLEAR },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({
      alignment: align,
      children: [new TextRun({ text, bold, color, size, font: "微软雅黑" })]
    })]
  });
}

function hCell(text, w = 2000, opts = {}) {
  return cell(text, { w, bg: BLUE, color: WHITE, bold: true, size: 18, ...opts });
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    pageBreakBefore: true,
    children: [new TextRun({ text, bold: true, size: 36, color: BLUE, font: "微软雅黑" })]
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, bold: true, size: 26, color: BLUE_MID, font: "微软雅黑" })]
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    children: [new TextRun({ text, bold: true, size: 22, color: GRAY, font: "微软雅黑" })]
  });
}

function p(text, opts = {}) {
  const { bold = false, color = "000000", size = 20, indent = 0 } = opts;
  return new Paragraph({
    indent: indent ? { left: indent } : undefined,
    children: [new TextRun({ text, bold, color, size, font: "微软雅黑" })]
  });
}

function gap() {
  return new Paragraph({ children: [new TextRun({ text: "", size: 12 })] });
}

function prdTable(headers, rows, widths) {
  const totalW = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: totalW, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) => hCell(h, widths[i], { align: AlignmentType.CENTER }))
      }),
      ...rows.map(r => new TableRow({
        children: r.map((v, i) => {
          const isObj = typeof v === 'object' && v !== null && !Array.isArray(v);
          if (isObj) {
            return cell(v.text, { w: widths[i], ...v });
          }
          return cell(String(v), { w: widths[i] });
        })
      }))
    ]
  });
}

